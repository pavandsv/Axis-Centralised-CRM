// ---------------------------------------------------------------------------
// Build-time: TopoJSON of India -> a tiny module of SVG path strings.
//
// Run: node scripts/build-india-map.mjs
//
// Source: https://github.com/udit-001/india-maps-data (topojson/india.json),
// vendored at scripts/data/india-topo.json so the build is reproducible
// offline. It carries all 36 states and union territories including Jammu and
// Kashmir and Ladakh — the full Indian claim, which is the correct boundary to
// show an Indian client.
//
// Projecting here rather than in the browser means the app ships no geo library
// and no 886 KB topology: just flat path strings it can render directly. The
// CSP on the hosted build blocks external fetches anyway.
// ---------------------------------------------------------------------------
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoMercator, geoPath } from 'd3-geo'

const WIDTH = 620
const HEIGHT = 680
const PRECISION = 1 // decimal places in path output — 0.1px is invisible at this size

const topo = JSON.parse(readFileSync(new URL('./data/india-topo.json', import.meta.url)))
const states = feature(topo, topo.objects.states)

const projection = geoMercator().fitExtent(
  [[8, 8], [WIDTH - 8, HEIGHT - 8]],
  states,
)
const path = geoPath(projection)

// Round coordinates: full float precision triples the file for sub-pixel detail.
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(+(+n).toFixed(PRECISION)))

const rows = states.features
  .map((f) => {
    const name = f.properties.st_nm
    const d = path(f)
    if (!d) return null
    const [cx, cy] = path.centroid(f)
    return {
      name,
      d: round(d),
      c: [+cx.toFixed(1), +cy.toFixed(1)],
      area: path.area(f),
    }
  })
  .filter(Boolean)
  // Draw big states first so small ones and UTs stay clickable on top.
  .sort((a, b) => b.area - a.area)

const out = `// AUTO-GENERATED by scripts/build-india-map.mjs — do not edit by hand.
// ${rows.length} states and union territories, Mercator, ${WIDTH}x${HEIGHT}.
// Source: github.com/udit-001/india-maps-data (see the build script).

export const MAP_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}'

/** { name, d: SVG path, c: [labelX, labelY] } — largest first. */
export const INDIA_STATES = ${JSON.stringify(rows.map(({ name, d, c }) => ({ name, d, c })))}

export const MAP_STATE_NAMES = INDIA_STATES.map((s) => s.name)
`

const target = new URL('../src/data/indiaMap.js', import.meta.url)
writeFileSync(target, out)
console.log(`${rows.length} states written · ${(out.length / 1024).toFixed(0)} KB`)
